-- 3.1 DIM_TEMPS
DROP TABLE IF EXISTS dim_temps;
CREATE TABLE dim_temps
STORED AS PARQUET AS
SELECT 
    CAST(DATE_FORMAT(d, 'yyyyMMdd') AS INT) AS id_temps,
    d AS date_complete,
    CAST(DAY(d) AS SMALLINT) AS jour,
    CAST(MONTH(d) AS SMALLINT) AS mois,
    CAST(DATE_FORMAT(d, 'MMMM') AS STRING) AS nom_mois,
    CAST(QUARTER(d) AS SMALLINT) AS trimestre,
    CAST(CASE WHEN MONTH(d) <= 6 THEN 1 ELSE 2 END AS SMALLINT) AS semestre,
    CAST(YEAR(d) AS SMALLINT) AS annee
FROM (
    SELECT EXPLODE(SEQUENCE(TO_DATE('2010-01-01'), TO_DATE('2030-12-31'), INTERVAL 1 DAY)) AS d
) t;